function applyLang(langData) {
    const elements = document.querySelectorAll('[data-lang]');
    elements.forEach((el) => {
        const key = el.getAttribute('data-lang');
        const value = key.split('.').reduce((oldVal, currentVal) => oldVal?.[currentVal], langData);
        if (value) {
            el.textContent = value;
        }
    });
}

function getLang() {
    return JSON.parse(localStorage.getItem('lang')) || 'vi';
}

function loadLang() {
    console.log("ALO")
    const lang = getLang();
    const data = lang === 'vi' ? window.translations.vi : window.translations.us;
    applyLang(data);
}
function setLang(lang = 'vi'){
    localStorage.setItem('lang',JSON.stringify(lang));  
    loadLang();
}


document.addEventListener("DOMContentLoaded", () => {
    loadLang();
});

function chageLang(){
    const vn = document.getElementById('btn_vn');
    vn.addEventListener('click',()=>{
        console.log("VN")
        setLang('vi');
    })

    const us = document.getElementById('btn_us');
    us.addEventListener('click',()=>{
        console.log("US")

        setLang('us');
    })
}
chageLang();